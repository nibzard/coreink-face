#!/usr/bin/env python3
"""Rasterize the repository's face manifest and an OFL font into flash assets."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
HERE = ROOT / "firmware"
OUTPUT = HERE / "components/coreink_core/generated/assets.hpp"
PRIMARY_FONT = HERE / "tools/ter-u20b.bdf"


def packed(image):
    """MSB first, one means black, each row padded to a byte boundary."""
    gray = image.convert("L")
    data = bytearray()
    for y in range(gray.height):
        for x in range(0, gray.width, 8):
            b = 0
            for bit in range(8):
                if x + bit < gray.width and gray.getpixel((x + bit, y)) < 128:
                    b |= 0x80 >> bit
            data.append(b)
    return bytes(data)


def array(name, data):
    rows = ["    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + "," for i in range(0, len(data), 24)]
    return f"inline constexpr uint8_t {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


def bitmap_glyphs():
    """Read the font's native pixels verbatim; no outline rasterization/scaling."""
    glyphs = {}
    cp = None
    advance = 0
    rows = None
    for line in PRIMARY_FONT.read_text().splitlines():
        if line.startswith("ENCODING "):
            cp = int(line.split()[1])
        elif line.startswith("DWIDTH "):
            advance = int(line.split()[1])
        elif line.startswith("BBX "):
            if tuple(map(int, line.split()[1:])) != (10, 20, 0, -4):
                raise ValueError("Unexpected bitmap font cell geometry")
        elif line == "BITMAP":
            rows = []
        elif line == "ENDCHAR":
            if rows is None or len(rows) != 20 or advance != 10:
                raise ValueError("Incomplete bitmap glyph")
            glyphs[cp] = (advance, b"".join(int(row, 16).to_bytes(2, "big") for row in rows))
            rows = None
        elif rows is not None:
            rows.append(line)
    return glyphs


def generate():
    from PIL import Image
    faces_dir = ROOT / "assets/faces"
    manifest = json.loads((faces_dir / "manifest.json").read_text())
    sources = {"assets/faces/manifest.json": hashlib.sha256((faces_dir / "manifest.json").read_bytes()).hexdigest()}
    output = ["// Generated by tools/generate_assets.py. Do not edit.\n#pragma once\n#include <cstdint>\nnamespace ink_assets {\ninline constexpr int face_size = 136;\ninline constexpr int glyph_width = 10;\ninline constexpr int glyph_height = 20;\ninline constexpr int line_height = 26;\n"]
    entries = []
    seen = set()
    for i, face in enumerate(manifest["faces"]):
        if face["id"] in seen:
            raise ValueError("duplicate face ID")
        seen.add(face["id"])
        path = faces_dir / face["file"]
        sources[str(path.relative_to(ROOT))] = hashlib.sha256(path.read_bytes()).hexdigest()
        png = subprocess.check_output(["rsvg-convert", "--width", "136", "--height", "136", "--background-color", "white", str(path)])
        image = Image.open(io.BytesIO(png)).convert("RGB")
        output.append(array(f"face_{i}", packed(image)))
        entries.append(f'    {{"{face["id"]}", face_{i}}},')
    output.append("struct Face { const char* id; const uint8_t* bits; };\ninline constexpr Face faces[] = {\n" + "\n".join(entries) + "\n};\n")
    available = bitmap_glyphs()
    codepoints = list(range(32, 127)) + list(range(160, 384)) + [0x2026]
    glyphs = []
    for cp in codepoints:
        if cp not in available:
            raise ValueError(f"font is missing U+{cp:04X}")
        glyphs.append(available[cp])
    output.append("struct Glyph { uint32_t codepoint; uint8_t advance; uint8_t rows[40]; };\ninline constexpr Glyph glyphs[] = {\n")
    for cp, (advance, data) in zip(codepoints, glyphs):
        output.append(f"    {{{cp}, {advance}, {{" + ",".join(f"0x{b:02x}" for b in data) + "}},\n")
    output.append("};\n} // namespace ink_assets\n")
    sources[str(PRIMARY_FONT.relative_to(ROOT))] = hashlib.sha256(PRIMARY_FONT.read_bytes()).hexdigest()
    sources["firmware/tools/FONT-LICENSE"] = hashlib.sha256((HERE / "tools/FONT-LICENSE").read_bytes()).hexdigest()
    sources[str(Path(__file__).resolve().relative_to(ROOT))] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    return "".join(output), sources


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="regenerate and compare tracked assets")
    parser.add_argument("--check-sources", action="store_true", help="verify source/output hashes without rasterizer dependencies")
    args = parser.parse_args()
    provenance = OUTPUT.with_name("sources.json")
    if args.check_sources:
        metadata = json.loads(provenance.read_text())
        for path, digest in metadata.items():
            file = OUTPUT if path == "_generatedSha256" else ROOT / path
            if hashlib.sha256(file.read_bytes()).hexdigest() != digest:
                raise SystemExit(f"Stale or modified generated assets: {path}")
        print("Generated asset provenance verified")
        return
    text, sources = generate()
    sources["_generatedSha256"] = hashlib.sha256(text.encode()).hexdigest()
    meta = json.dumps(sources, indent=2, sort_keys=True) + "\n"
    if args.check:
        if OUTPUT.read_text() != text or provenance.read_text() != meta:
            raise SystemExit("Generated assets are stale; run firmware/tools/generate_assets.py")
        print("Face and font assets match sources")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text)
        provenance.write_text(meta)
        print("Generated 35 faces and 320 native bitmap font glyphs")


if __name__ == "__main__":
    main()
